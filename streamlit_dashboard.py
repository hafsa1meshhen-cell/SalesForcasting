        fig, ax = plt.subplots(figsize=(14, 6))
        
        months = range(len(hist_df))
        ax.plot(months, hist_df['Actual_Sales'], marker='o', label='Actual Sales', 
               linewidth=2, color='#2ecc71', markersize=5)
        ax.plot(months, hist_df['Predicted_Sales'], marker='s', label='Predicted Sales', 
               linewidth=2, color='#e74c3c', markersize=4)
        
        ax.fill_between(months, hist_df['Actual_Sales'], hist_df['Predicted_Sales'],
                        alpha=0.2, color='gray')
        
        ax.set_xlabel('Month Index', fontsize=12)
        ax.set_ylabel('Sales ($)', fontsize=12)
        ax.set_title('Historical: Actual vs Predicted Sales', fontsize=14, fontweight='bold')
        ax.legend(loc='best', fontsize=10)
        ax.grid(True, alpha=0.3)
        plt.tight_layout()
        
        st.pyplot(fig)
        
        # Residuals Analysis
        st.subheader("📊 Residuals Analysis")
        
        fig, axes = plt.subplots(1, 2, figsize=(14, 5))
        
        # Residuals over time
        axes[0].plot(months, hist_df['Error'], marker='o', color='#f39c12', linewidth=2)
        axes[0].axhline(y=0, color='red', linestyle='--', linewidth=1)
        axes[0].fill_between(months, hist_df['Error'], 0, alpha=0.3, color='#f39c12')
        axes[0].set_xlabel('Month Index', fontsize=11)
        axes[0].set_ylabel('Error ($)', fontsize=11)
        axes[0].set_title('Residuals Over Time', fontsize=12, fontweight='bold')
        axes[0].grid(True, alpha=0.3)
        
        # Error distribution
        axes[1].hist(hist_df['Error'], bins=15, color='#3498db', alpha=0.7, edgecolor='black')
        axes[1].axvline(x=hist_df['Error'].mean(), color='red', linestyle='--', 
                       linewidth=2, label=f"Mean: ${hist_df['Error'].mean():,.0f}")
        axes[1].set_xlabel('Error ($)', fontsize=11)
        axes[1].set_ylabel('Frequency', fontsize=11)
        axes[1].set_title('Error Distribution', fontsize=12, fontweight='bold')
        axes[1].legend()
        axes[1].grid(True, alpha=0.3, axis='y')
        
        plt.tight_layout()
        st.pyplot(fig)
        
        # Performance metrics
        st.subheader("📊 Detailed Metrics")
        
        col1, col2, col3, col4, col5 = st.columns(5)
        
        with col1:
            st.metric("Mean Error", f"${hist_df['Error'].mean():,.0f}")
        with col2:
            st.metric("Std Dev Error", f"${hist_df['Error'].std():,.0f}")
        with col3:
            st.metric("Min Error", f"${hist_df['Error'].min():,.0f}")
        with col4:
            st.metric("Max Error", f"${hist_df['Error'].max():,.0f}")
        with col5:
            st.metric("R² Score", f"{(1 - np.var(hist_df['Error']) / np.var(hist_df['Actual_Sales'])):.4f}")

