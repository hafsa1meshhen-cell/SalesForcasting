# TAB 2: FORECAST
# ============================================================

with tab2:
    st.header("📈 Future Sales Forecast (12 Months)")
    
    if 'forecast' in data:
        forecast_df = data['forecast'].copy()
        
        # Display forecast table
        if st.checkbox("Show Forecast Data Table"):
            st.dataframe(forecast_df, use_container_width=True)
        
        # Forecast visualization
        st.subheader("📊 Forecast Chart")
        
        fig, ax = plt.subplots(figsize=(12, 6))
        
        # Convert Month to datetime for plotting
        forecast_df['Month'] = pd.to_datetime(forecast_df['Month'])
        
        ax.plot(forecast_df['Month'], forecast_df['Forecast_Sales'], 
                marker='o', linewidth=2, label='Forecast Sales', color='#667eea')
        ax.plot(forecast_df['Month'], forecast_df['Target_Sales'], 
                marker='s', linewidth=2, label='Target Sales', color='#764ba2')
        ax.fill_between(forecast_df['Month'], 
                         forecast_df['Lower_Bound'], 
                         forecast_df['Upper_Bound'],
                         alpha=0.2, color='#667eea', label='70% Confidence Band')
        
        ax.set_xlabel('Month', fontsize=12)
        ax.set_ylabel('Sales ($)', fontsize=12)
        ax.set_title('12-Month Sales Forecast with Target Rule', fontsize=14, fontweight='bold')
        ax.legend(loc='best')
        ax.grid(True, alpha=0.3)
        plt.xticks(rotation=45)
        plt.tight_layout()
        
        st.pyplot(fig)
        
        # Forecast statistics
        st.subheader("📊 Forecast Statistics")
        col1, col2, col3, col4 = st.columns(4)
        
        with col1:
            st.metric("Avg Forecast", f"${forecast_df['Forecast_Sales'].mean():,.0f}")
        with col2:
            st.metric("Avg Target", f"${forecast_df['Target_Sales'].mean():,.0f}")
        with col3:
            st.metric("Min Forecast", f"${forecast_df['Forecast_Sales'].min():,.0f}")
        with col4:
            st.metric("Max Forecast", f"${forecast_df['Forecast_Sales'].max():,.0f}")
        
        # Regressor values
        st.subheader("🔧 Future Regressor Values")
        regressors = [col for col in forecast_df.columns if col not in 
                     ['Month', 'Forecast_Sales', 'Target_Sales', 'Lower_Bound', 'Upper_Bound']]
        
        if regressors:
            selected_regressor = st.selectbox("Select Regressor to Visualize", regressors)
            
            if selected_regressor:
                fig, ax = plt.subplots(figsize=(12, 5))
                ax.plot(forecast_df['Month'], forecast_df[selected_regressor], 
                       marker='o', linewidth=2, color='#667eea')
                ax.set_xlabel('Month', fontsize=11)
                ax.set_ylabel(selected_regressor, fontsize=11)
                ax.set_title(f"{selected_regressor} Projection", fontsize=13, fontweight='bold')
                ax.grid(True, alpha=0.3)
                plt.xticks(rotation=45)
                plt.tight_layout()
                st.pyplot(fig)

