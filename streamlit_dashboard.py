# ============================================================
# LOAD DATA
# ============================================================

def load_data():
    """Load CSV files generated by forecast_backup.py"""
    data = {}
    
    try:
        # Load forecast results
        if os.path.exists("prophet_sales_forecast_results.csv"):
            data['forecast'] = pd.read_csv("prophet_sales_forecast_results.csv")
        
        # Load historical performance
        if os.path.exists("prophet_historical_performance.csv"):
            data['historical'] = pd.read_csv("prophet_historical_performance.csv")
        
        # Load synthetic data
        if os.path.exists("territory_single_prophet_ready.csv"):
            data['synthetic'] = pd.read_csv("territory_single_prophet_ready.csv")
    
    except Exception as e:
        st.error(f"Error loading data: {e}")
    
    return data

data = load_data()

# ============================================================
# KEY METRICS
# ============================================================

st.sidebar.markdown("---")
st.sidebar.header("🎯 Key Metrics")

if 'historical' in data:
    hist_df = data['historical']
    
    # Calculate metrics
    rmse = np.sqrt(np.mean(hist_df['Error']**2))
    mean_sales = hist_df['Actual_Sales'].mean()
    rmse_pct = (rmse / mean_sales * 100) if mean_sales != 0 else 0
    mape = hist_df['Percentage_Error'].abs().mean()
    mae = hist_df['Absolute_Error'].mean()
    
    col1, col2 = st.sidebar.columns(2)
    with col1:
        st.metric("RMSE %", f"{rmse_pct:.2f}%", delta="Excellent" if rmse_pct < 5 else "Good")
    with col2:
        st.metric("MAPE", f"{mape:.2f}%")
    
    col3, col4 = st.sidebar.columns(2)
    with col3:
        st.metric("MAE", f"${mae:,.0f}")
    with col4:
        st.metric("Mean Sales", f"${mean_sales:,.0f}")

